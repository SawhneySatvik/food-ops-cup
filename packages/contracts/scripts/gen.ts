// date-time / date keep their exact text in Python: drop `format` (which would become datetime/date and
// re-serialise "+00:00" as "Z") and keep the zod regex as the check.
function pythonView(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(pythonView);
  if (node === null || typeof node !== "object") return node;
  const out: Json = {};
  for (const [k, v] of Object.entries(node as Json)) out[k] = pythonView(v);
  if ((out.format === "date-time" || out.format === "date") && typeof out.pattern === "string") delete out.format;
  return out;
}
