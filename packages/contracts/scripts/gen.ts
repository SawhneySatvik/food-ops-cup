type Json = Record<string, unknown>;
const write = (p: string, body: string) => writeFileSync(p, body.endsWith("\n") ? body : body + "\n");
const json = (v: unknown) => JSON.stringify(v, null, 2);
const step = (msg: string) => console.log(`gen: ${msg}`);
const fresh = (dir: string) => {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
};

const reg = await loadRegistry();

// JS `\d` is ASCII; Rust/Python `\d` is Unicode. Spell digits out so every consumer accepts the same set.
const digits = (j: Json) => {
  if (typeof j.pattern === "string") j.pattern = j.pattern.replaceAll("\\d", "[0-9]");
};
const plain = (s: z.ZodType) => {
  const { $schema: _s, ...rest } = z.toJSONSchema(s, { target: "draft-2020-12", io: "input", override: ({ jsonSchema }) => digits(jsonSchema as Json) }) as Json;
  return rest;
};
// A draft-payload position (shared/draftables.ts) becomes `anyOf` of every registered draftable's proposal
// or editable schema, so JSON Schema / Pydantic never see an open object where a payload belongs.
const draftAnyOf = (kind: DraftPayloadKind): Json => ({ anyOf: draftableTypes().map((t) => plain(draftable(t)![kind])) });
const override = ({ jsonSchema }: { jsonSchema: Json }) => {
  digits(jsonSchema);
  const kind = jsonSchema[DRAFT_PAYLOAD_META] as DraftPayloadKind | undefined;
  if (kind) {
    for (const k of Object.keys(jsonSchema)) delete jsonSchema[k];
    Object.assign(jsonSchema, { [DRAFT_PAYLOAD_META]: kind, ...draftAnyOf(kind) });
  }
};
const toJson = (s: z.ZodType) => z.toJSONSchema(s, { target: "draft-2020-12", io: "input", override }) as Json;
step(`draftable command types: ${draftableTypes().join(", ")}`);
step(`${reg.modules.length} modules: ${reg.modules.join(", ")}`);

// 1 · one standalone JSON Schema per contract name ---------------------------------------------------
fresh(JSON_DIR);
for (const [name, schema, module] of reg.schemas) {
  const { $schema, ...rest } = toJson(schema);
  write(join(JSON_DIR, `${name}.schema.json`), json({ $schema, $id: name, title: pascal(name), "x-munim-module": module, ...rest }));
}
step(`${reg.schemas.length} JSON Schema files → generated/json-schema/`);

// 2 · OpenAPI 3.1 — components share $refs between registered schemas ------------------------------------
const registry = z.registry<{ id: string }>();
for (const [name, schema] of reg.schemas) registry.add(schema, { id: name });
const bundle = z.toJSONSchema(registry, {
  target: "draft-2020-12",
  io: "input",
  override,
  uri: (id) => `#/components/schemas/${pascal(id)}`,
}) as { schemas: Record<string, Json> };
const components: Record<string, Json> = {};
for (const [name, , module] of reg.schemas) {
  const { $schema: _s, $id: _i, ...body } = bundle.schemas[name]!;
  components[pascal(name)] = { title: pascal(name), "x-munim-contract": name, "x-munim-module": module, ...body };
}
const ref = (name: string) => ({ $ref: `#/components/schemas/${pascal(name)}` });
const UUID_PARAM = (components.Uuid7 as Json) ?? { type: "string" };
// 400 = a body that is not JSON, a bad query/path value or a missing header; 422 = valid JSON that is not a valid
// command/payload (`invalid_payload`). Both can come from any operation (R3-M6).
const ERRORS: Record<string, string> = { "400": "Bad request", "401": "Unauthenticated", "403": "Not allowed", "404": "Not found", "422": "Validation failed" };
const idempotencyKey = (() => {
  const { $schema: _s, ...k } = toJson(IdempotencyKey);
  return k;
})();

function requestBody(r: Route): Json | undefined {
  if (r.command) {
    const envelope = {
      type: "object",
      title: `${pascal(r.command)}Command`,
      properties: { command_id: ref("uuid7"), idempotency_key: idempotencyKey, type: { type: "string", const: r.command }, payload: ref(r.command) },
      required: ["command_id", "idempotency_key", "type", "payload"],
      additionalProperties: false,
    };
    return { required: true, content: { "application/json": { schema: envelope } } };
  }
  return r.request ? { required: true, content: { "application/json": { schema: ref(r.request) } } } : undefined;
}

const SECURITY: Record<Route["auth"], Json[]> = {
  member: [{ memberToken: [], tenantHeader: [] }],
  operator: [{ operatorToken: [] }],
  identity: [{ memberToken: [] }],
  intel: [{ runToken: [], serviceCredential: [] }],
  storefront: [{ storefrontKey: [] }, { storefrontKey: [], customerToken: [] }],
  // An empty list is "no authentication" in OpenAPI; an omitted `security` would inherit, so it is explicit.
  public: [],
};

function operation(r: Route): Json {
  const parameters = [
    ...(r.pathParams ?? []).map((p) => ({ name: p.name, in: "path", required: true, schema: p.uuid ? { type: "string", pattern: UUID_PARAM.pattern } : { type: "string" } })),
    ...(r.query ?? []).map((q) => ({ name: q.name, in: "query", required: q.required, schema: q.schema })),
  ];
  const errors = { ...ERRORS, ...(r.conflict ? { "409": "Conflict" } : {}) };
  const errorSchema = (code: string) => (r.errors && (code === "409" || code === "422") ? r.errors : "error");
  const body = requestBody(r);
  // A stream's 200 is text/event-stream; each `data:` line is the JSON of `response` (seeded into the pruned
  // components below, so the SDK still types it).
  const ok: Json = r.stream
    ? { description: `OK — server-sent events; each \`data:\` line is the JSON of ${pascal(r.response)} (read with the SDK's openStream, never EventSource)`, content: { "text/event-stream": { schema: { type: "string" } } } }
    : { description: "OK", content: { "application/json": { schema: ref(r.response) } } };
  // A command's response body is stored once and replayed byte-identically; a replay is marked by header.
  if (r.command) ok.headers = { [REPLAYED_HEADER]: { description: "\"true\" when this is the stored response of an earlier identical request", schema: { type: "string", enum: ["true"] } } };
  return {
    operationId: r.operationId,
    summary: r.summary,
    security: [...SECURITY[r.auth], ...(r.guest ? [{ storefrontKey: [], guestToken: [] }] : []), ...(r.alsoAuth ?? []).flatMap((a) => SECURITY[a])],
    ...(parameters.length ? { parameters } : {}),
    ...(body ? { requestBody: body } : {}),
    responses: {
      [String(r.status)]: ok,
      ...Object.fromEntries(Object.entries(errors).map(([c, d]) => [c, { description: d, content: { "application/json": { schema: ref(errorSchema(c)) } } }])),
    },
  };
}

function openapi(surface: Surface | "all", schemas: Record<string, Json>): Json {
  const paths: Record<string, Json> = {};
  const used = new Set<string>();
  for (const r of reg.routes.filter((x) => surface !== "all" && x.surface === surface)) {
    const op = operation(r);
    for (const set of op.security as Json[]) for (const k of Object.keys(set)) used.add(k);
    (paths[r.path] ??= {})[r.method] = op;
  }
  return {
    openapi: "3.1.0",
    info: {
      title: surface === "internal" ? "Munim core-api — /internal/intel/v1" : "Munim core-api — /v1 and /platform/v1",
      version: "w1",
      description: `${HEADER} All data is synthetic; suppliers are simulated; payments are recorded, never processed.`,
    },
    jsonSchemaDialect: "https://json-schema.org/draft/2020-12/schema",
    paths,
    components: {
      schemas,
      securitySchemes: surface === "public" ? Object.fromEntries(Object.entries(SECURITY_SCHEMES).filter(([k]) => used.has(k))) : SECURITY_SCHEMES,
    },
  };
}
/** Every credential scheme; public.json keeps only those its operations name (no run token or service credential). */
const SECURITY_SCHEMES: Json = {
  memberToken: { type: "http", scheme: "bearer", description: "IdP ID token of a signed-in person (a tenant member; alone on identity routes)" },
  operatorToken: { type: "http", scheme: "bearer", description: "IdP ID token of a platform operator" },
  runToken: { type: "http", scheme: "bearer", bearerFormat: "JWT (EdDSA)", description: "Run token minted by core-api (Ed25519)" },
  serviceCredential: { type: "apiKey", in: "header", name: "x-munim-service-secret", description: "Service-to-service credential of the intel service" },
  tenantHeader: { type: "apiKey", in: "header", name: TENANT_HEADER, description: "The tenant a member acts in (with memberToken)" },
  storefrontKey: { type: "apiKey", in: "header", name: STOREFRONT_KEY_HEADER, description: "Public storefront key; resolves the tenant and channel" },
  customerToken: { type: "http", scheme: "bearer", description: "IdP ID token of a customer (optional on storefront routes)" },
  guestToken: { type: "apiKey", in: "header", name: GUEST_TOKEN_HEADER, description: "Guest access token of one order (returned once when the guest places it); with storefrontKey, on routes that mark guest access" },
};
/** The components a surface's operations reach: every schema a route names (response, request, command, errors — a
 *  stream's event schema has no $ref in its operation) and everything its operations and those schemas $ref, transitively. */
function reachable(surface: Surface): Record<string, Json> {
  const seen = new Set<string>();
  const visit = (name: string) => {
    if (seen.has(name)) return;
    seen.add(name);
    walk(components[name]);
  };
  const walk = (node: unknown): void => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (node === null || typeof node !== "object") return;
    for (const [k, v] of Object.entries(node)) {
      if (k === "$ref" && typeof v === "string" && v.startsWith("#/components/schemas/")) visit(v.slice("#/components/schemas/".length));
      else walk(v);
    }
  };
  const routes = reg.routes.filter((r) => r.surface === surface);
  for (const n of routes.flatMap((r) => [r.response, r.request, r.command, r.errors])) if (n) visit(pascal(n));
  for (const r of routes) walk(operation(r));
  const missing = [...seen].filter((n) => !components[n]);
  if (missing.length) throw new Error(`${surface}: $ref to unknown components: ${missing.join(", ")}`);
  return Object.fromEntries(Object.entries(components).filter(([n]) => seen.has(n)));
}
